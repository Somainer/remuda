#!/usr/bin/env node
/**
 * Generate `src/lib/secretShapes.generated.ts` from the ONE shared list,
 * `scripts/ci/secret-shapes.json` (read by the gate scan and the Hub's secret
 * lint). The web redactor imports the generated module, so a browser never
 * carries a second, weaker list of credential shapes.
 *
 * The JSON patterns are Python `re` syntax that JavaScript also accepts
 * (lookbehind, `\b`, character classes). `dummyPart` carries an inline `(?i)`
 * flag, which JS spells as the `i` flag; the generated module keeps the raw
 * pattern and the redactor compiles it with that flag stripped.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const shapesPath = join(root, "../scripts/ci/secret-shapes.json");
const outPath = join(root, "src/lib/secretShapes.generated.ts");

const shapes = JSON.parse(readFileSync(shapesPath, "utf8"));
const rules = shapes.rules ?? [];
const literal = (value) => JSON.stringify(value);

const body = `// Generated by scripts/gen-secret-shapes.mjs from scripts/ci/secret-shapes.json.
// Do not edit: change the shared JSON and regenerate (pnpm gen:secret-shapes).
// secretShapes.test.ts fails if this file drifts from the JSON.

/** One shared credential-shape rule. */
export type SecretShapeRule = {
  readonly name: string;
  readonly pattern: string;
  readonly minPayload: number;
};

/** The shared candidate shapes, in the JSON's order. */
export const SECRET_SHAPE_RULES: readonly SecretShapeRule[] = [
${rules
  .map(
    (rule) =>
      `  { name: ${literal(rule.name)}, pattern: ${literal(rule.pattern)}, minPayload: ${Number(rule.minPayload)} },`,
  )
  .join("\n")}
];

/** Characters that already read as masked (the scan's \`mask\`). */
export const SECRET_SHAPE_MASK = ${literal(shapes.mask ?? "")};

/** A value that is a placeholder rather than a credential. */
export const SECRET_SHAPE_PLACEHOLDER = ${literal(shapes.placeholder ?? "")};

/** Docs/fixture names that merely resemble a credential. */
export const SECRET_SHAPE_DUMMY_PART = ${literal(shapes.dummyPart ?? "")};
`;

writeFileSync(outPath, body);
